ASSEMBLABLE = {"candidate_ready", "assembly_ready"}

REQUIREMENTS_POLICY = '''
Requirement sources must be distinguished: the original text, the source package and the read-only fixed_contract are user-supplied constraints; job.requirements and plan are generated by the planning model.
Tentative positions, spacings, heights, footprints, etc. proposed by the planning model are design assumptions and are not automatically promoted to hard user specifications.
When the source package explicitly allows dimensions to be settled jointly, or the plan calls them tentative/modelling layout values, they may be adjusted to the actual dependency geometry;
recording the basis and the new interface in the manifest is sufficient; changes to the model's own design values need no human approval.
A review must not demand repair/uncertain merely because such tentative values were departed from; it must point to an explicit conflict with the original sources or fixed_contract.
Equally, design freedom must not be used to change instrument dimensions fixed by the sources, scale dependency models, fabricate measurements or waive engineering checks.
When numbers/terms are ambiguous, interpret them using the original context and the dependency's actual local coordinate definitions; do not confuse a tube instance's origin with the flange support face.
'''

ASSET_SCOPE = '''
This stage is the body review of a single asset/device: its shape, its internal fits and all of its own motion mechanisms must be fully judged in this stage and cannot be deferred.
verdict may only be accept or repair. Body problems (missing parts, wrong shape or mechanism, visible interpenetration or floating, conflict with the sources, poor internal fit,
missing mechanism or implausible motion) always mean repair. accept only when everything inside this asset has been verified correct.
Cross-instance matters (plugging into other assets, placement into other instruments, tabletop support and overall occlusion) do not belong to this stage; write them to
deferred:[{"stage":"scene|operation","detail":"what specifically remains to be verified"}] (each item has exactly these two keys): stage="scene" for cross-instance fit,
stage="operation" for robot grasping, operation sequences and trajectories. These records may coexist with accept and are completed by the corresponding stage,
but body defects must not be written into deferred.
You must return motion_coverage:[{"requirement":"verbatim text of one motion/interaction requirement from the sources","mechanism":"id of the mechanism in interfaces.json that implements it, or null",
"verdict":"ok|missing|wrong","evidence":"basis: mechanism sweep/actuation/lock/release check ids and renders of both mechanism extremes"}],
covering, one entry each, every motion requirement of this asset's body in the sources' Required interactions and the task requirements (open/close, slide, rotate, swing, press, lock/unlock, remove/refit, etc.).
Any missing or wrong requires repair and an entry in findings. If any numeric check mechanism_*, sampled_joint_sweep:*, release_probe:* or numerical_stability is fail, repair is required.
Dimensions not bound to an exact numeric check go into unverified; exact compliance must not be concluded from images alone.
reference_policy and evidence state exactly which images were supplied; do not treat a standalone render of a dependency as a combined assembly image.
Use uncertain only when images cannot be opened or the sources contradict themselves so that no judgement is possible at all, and add blocking:["specific reason"].
Keep the three base fields verdict/findings/unverified; motion_coverage is required; blocking and deferred are optional additional fields.
If instance_contract.expected_model_units is non-empty, you must add a prototype_units field reporting, from the current actual geometry/renders, the number of complete asset units within a single model.
Parts, lids and internal mechanisms are not separate asset units. Several complete tubes are several units; the scene does the replication, so a model must not replicate the full count again inside itself.
A per-model count mismatch requires repair; if image or geometry evidence is insufficient to count, set prototype_units=null with uncertain and blocking; never assume the count is satisfied.
'''

SCENE_SCOPE = '''
This is the review of a complete candidate scene; handle every item in deferred_checks with stage="scene".
Add deferred_results:[{"id":"pending item id copied verbatim","status":"resolved|unresolved","evidence":"basis: specific renders and check entries; if insufficient, state why"}].
Each scene item must be answered exactly once. accept only if all are resolved with evidence and this round's engineering checks pass.
If concrete defects remain, use repair and add affected_instances:["actual instance id"], explicitly listing the instances to adjust or repair.
For defects of the layout itself use affected_layout:["robot_home"|"table:actual table id"|"dock:actual dock id"],
referencing only objects listed in layout_review_targets. This field authorizes layout coordination, not changes to robot or instrument geometry.
repair must name at least one instance or layout object; for any other verdict both lists must be empty.
Use only full ids from plan.instances, never asset ids or substrings; findings describe defects, and repair permissions are never guessed from their text.
For accept/uncertain, affected_instances must be omitted or empty. If evidence is still insufficient, use uncertain and give blocking.
Exact dimensions, skipped dynamics, complete operations and trajectories cannot be proven from images alone. Items with stage="operation" stay unverified, must not be claimed resolved, and do not block the current static scene.
This stage must not defer scene items to scene again, nor delete or rename them to evade checks.
Exception, only for review_scope.validation_mode="static": this round delivers a preview of the current initial geometric layout.
Currently visible missing parts, wrong asset counts, wrong shapes, penetration, floating and explicit static dimension conflicts must be handled and cannot be skipped under the exception.
Items that can only be proven by configuring the protocol's initial joint/content states, switching to another assembly pose or contact position, or executing operations
may use status="out_of_scope" in deferred_results, adding target_stage="initial_state|static_fit|operation", with evidence stating clearly what is still missing.
These items stay unverified and are never marked resolved. As long as the current layout looks acceptable, no engineering check is fail, and every remaining item is explicitly assigned this way, accept to deliver the static preview.
Every engineering check entry with status="fail" or "partial" must be handled: repair what can be repaired; assign items that truly belong to a later stage per the rules above, with an explanation.
Do not require inserting tubes into instruments, grasping, removing and parking lids, or configuring contents before the current static layout can be judged; full mode does not allow this exception.
'''


def scoped_review(value, stage, deferred=(), expected_units=None, preview=False, instance_ids=None, layout_targets=()):
    try:
        return _scoped_review(value,stage,deferred,expected_units,preview,instance_ids,layout_targets)
    except ValidationError as exc:
        if stage=="scene" and isinstance(value,dict):
            expected={d["id"] for d in deferred if d["stage"]=="scene"}
            accepted,errors=resolution_feedback(value.get("deferred_results",[]),expected,stage,preview)
            exc.accepted_results=list(accepted.values())
            exc.review_feedback={"invalid":errors,"missing_ids":sorted(expected-set(accepted)),"retained_ids":sorted(accepted)}
        raise


def _scoped_review(value, stage, deferred=(), expected_units=None, preview=False, instance_ids=None, layout_targets=()):
    require(isinstance(value, dict), "Stage review must be an object")
    required = {"verdict", "findings", "unverified"}
    allowed = required | {"deferred", "blocking", "deferred_results", "prototype_units", "motion_coverage"}
    if stage == "scene":
        allowed.update({"affected_instances", "affected_layout"})
    require(required <= set(value) <= allowed, "Invalid stage review fields: missing="+str(sorted(required-set(value)))+"; unknown="+str(sorted(set(value)-allowed)))
    require(stage in {"asset", "scene"} and isinstance(value["verdict"], str), "Invalid review stage or verdict")
    require(value["verdict"] != "defer", "Asset and scene reviews no longer use defer: body problems are repair; write cross-instance matters to deferred and give accept or repair")
    base = {k: value[k] for k in required}
    visual_result(base)  # A defect list cannot coexist with accept.
    if stage == "asset":
        motion_coverage(value)
    if expected_units is not None:
        units = value.get("prototype_units")
        # A multi-configuration model may report one count per configuration.
        counts = list(units.values()) if isinstance(units, dict) and units else [units]
        require("prototype_units" in value and (all(type(u) is int and u > 0 for u in counts)
                                                or units is None and value["verdict"] == "uncertain"),
                "Repeated-instance jobs must report prototype_units: the number of complete asset units in one model "
                "(an integer, or {configuration: integer})")
        require(value["verdict"] in {"repair", "uncertain"} or all(u == expected_units for u in counts),
                "The number of asset units in one model does not match; cannot accept")
    pending = value.get("deferred", [])
    require(isinstance(pending, list) and len(pending) <= 64, "deferred must be a bounded list")
    pending = value["deferred"] = [deferred_item(item) for item in pending]
    for item in pending:
        require(set(item) == {"stage", "detail"}
                and isinstance(item["stage"], str) and item["stage"] in {"scene", "operation"}
                and isinstance(item["detail"], str) and 0 < len(item["detail"].strip()) <= 4000,
                'Each deferred item must be {"stage":"scene|operation","detail":"specific content"}; received: '+str(item)[:200])
    require(not pending or stage == "asset", "The scene stage cannot defer items again")
    blocking = value.get("blocking", [])
    require(isinstance(blocking, list) and all(isinstance(x, str) and x.strip() for x in blocking), "blocking must be a list of text reasons")
    require(value["verdict"] != "uncertain" or blocking,
            "uncertain must state this stage's blocking reasons; write cross-instance matters to deferred and unverified operations to unverified")
    require(value["verdict"] == "uncertain" or not blocking, "A verdict other than uncertain cannot include blocking reasons")
    require(value["verdict"] != "repair" or value["findings"], "repair must list this stage's concrete defects in findings")
    if stage == "asset":
        # The author edits from these lines alone: each must name the part, the evidence and the change.
        vague = [f for f in value["findings"] if not (":" in f and "evidence" in f.lower() and "suggested fix" in f.lower())]
        require(not vague, "Each finding must read \"part/geom name: problem; evidence (which image or which check); suggested fix "
                "(direction, value or structure)\"; not conforming: "+str(vague[:3])[:600])
    if stage == "scene":
        affected = value.get("affected_instances",[])
        require(isinstance(affected,list) and len(affected) <= 128 and all(isinstance(i,str) for i in affected)
                and len(affected) == len(set(affected)), "affected_instances must be a bounded list without duplicates")
        layout = value.get("affected_layout", [])
        require(isinstance(layout,list) and len(layout)<=289 and all(isinstance(i,str) for i in layout)
                and len(layout)==len(set(layout)) and set(layout)<=set(layout_targets), "affected_layout references unknown or duplicate objects")
        require(value["verdict"] != "repair" or affected or layout, "A scene repair must give affected_instances or affected_layout")
        require(value["verdict"] == "repair" or not layout, "A verdict other than repair cannot request layout change permission")
        require(value["verdict"] == "repair" or not affected, "A verdict other than repair cannot request instance change permission")
        require(not affected or instance_ids is not None and set(affected) <= set(instance_ids), "Repair references instance ids that do not exist")
    resolutions = value.get("deferred_results", [])
    expected = {d["id"] for d in deferred if d["stage"] == "scene"}
    accepted, errors = resolution_feedback(resolutions, expected, stage, preview)
    missing = sorted(expected - set(accepted)) if stage == "scene" else []
    if errors or missing:
        raise ValidationError("Invalid deferred_results: " + str({"invalid":errors,"missing_ids":missing}))
    require(value["verdict"] != "accept" or all(r["status"] in {"resolved","out_of_scope"} for r in resolutions),
            "Unresolved scene items remain; cannot accept")
    return value


def deferred_item(item):
    """One deferred item as {stage, detail}; a quoted requirement is folded into the detail text."""
    if not isinstance(item, dict) or not set(item) <= {"stage", "detail", "requirement"}:
        return item
    parts = [item[k].strip() for k in ("requirement", "detail") if isinstance(item.get(k), str) and item[k].strip()]
    return {"stage": item.get("stage"), "detail": ": ".join(parts)}


def motion_coverage(value):
    """Per-requirement motion verdicts; any gap forces repair with a finding."""
    rows = value.get("motion_coverage")
    if rows is None and value["verdict"] != "accept":
        return []
    require(isinstance(rows, list) and len(rows) <= 128, "An asset review accept must return a motion_coverage list (an empty list when there are no motion requirements)")
    for row in rows:
        require(isinstance(row, dict) and set(row) == {"requirement", "mechanism", "verdict", "evidence"}
                and isinstance(row["requirement"], str) and row["requirement"].strip()
                and (row["mechanism"] is None or isinstance(row["mechanism"], str))
                and row["verdict"] in {"ok", "missing", "wrong"} and isinstance(row["evidence"], str) and row["evidence"].strip(),
                "Each motion_coverage entry must contain requirement, mechanism, verdict (ok|missing|wrong) and evidence")
    bad = [r for r in rows if r["verdict"] != "ok"]
    require(not bad or (value["verdict"] == "repair" and value["findings"]),
            "A missing or wrong motion mechanism requires repair with an entry in findings")
    return rows


def deferred_records(review, job, version):
    return [{"id": f"{job}:{version}:{i}", "job": job, "stage": item["stage"],
             "detail": item["detail"], "status": "pending"}
            for i, item in enumerate(review.get("deferred", []), 1)]


def resolution_feedback(resolutions, expected, stage="scene", preview=False):
    """Validate independent answers; an ambiguous duplicate is never retained."""
    if not isinstance(resolutions,list):
        return {}, [{"field":"deferred_results","error":"must be a list"}]
    accepted, errors, seen = {}, [], set()
    for index, row in enumerate(resolutions):
        key = row.get("id") if isinstance(row,dict) else None
        try:
            require(stage=="scene" and isinstance(row,dict), "Only a scene review may return deferred_results")
            require({"id","status","evidence"} <= set(row) <= {"id","status","evidence","target_stage"}, "Item fields must be id/status/evidence plus target_stage when needed")
            require(isinstance(key,str) and key in expected, "Unknown item id; use only the pending item ids of this batch")
            require(key not in seen, "Duplicate id in the same response; give a single verdict again")
            require(row["status"] in ("resolved","unresolved","out_of_scope"), "status may only be resolved/unresolved/out_of_scope")
            require(isinstance(row["evidence"],str) and row["evidence"].strip(), "Specific evidence or the reason it is unresolved is required")
            if row["status"]=="out_of_scope":
                require(preview and row.get("target_stage") in ("initial_state","static_fit","operation"),
                        "Only the static scope may explicitly hand off to initial_state/static_fit/operation; such items cannot be marked resolved")
            else:
                require("target_stage" not in row, "target_stage is allowed only with out_of_scope")
            accepted[key]=row
        except ValidationError as exc:
            if isinstance(key,str): accepted.pop(key,None)
            errors.append({"index":index,"id":key,"error":str(exc)})
        if isinstance(key,str): seen.add(key)
    return accepted, errors
